//! Lean statements of the RV64 Wasm problems (`wasm-sim-rv reduce ... --lean DIR`): one Wasm spec
//! library entry (`Silmaril/WasmSpec/<Entry>`, status `stated`) per function with a `lean_spec`
//! in the plan, in the style of `Silmaril.WasmSpec.*` and of the x86 reduction generator
//! (`reduce::lean`). The P-locals module is self-contained except for its imports: the memory
//! `env.memory` (functions with loads/stores or calls) and its callees, which are assumed to meet
//! their own entries' `CallSpec` (assume-guarantee).
//!
//! Forms. Variables: the parameters by ABI name (`a0 a1 … ra sp s0 …` : `BitVec 64`), results
//! `r_a0 r_t0 …`, and for memory functions the bytes `B` (entry) and `B'` (return) of memory 0.
//! * pure (no memory import): `Spec` is body-level total correctness: from `Pre a…` the body can
//!   return `[.i64 r_a0, …]` with `Post a… r…`, store unchanged;
//! * memory: from a store `s` with `Inv s` and `MemAt s m ma mt B`, it can return with
//!   `Inv s'`, `MemAt s' m ma mt B'` and `Post B B' a… r…`; callees are hypotheses
//!   `<Callee>.CallSpec P host Inv m ma mt addr` on the imported function addresses.

use super::reduce::{ABI, Output};
use std::fmt::Write as _;
use wasmtime::error::Result;

pub struct LeanFn<'a> {
    pub entry: &'a str,
    pub func: &'a str,
    pub pre: &'a str,
    pub post: &'a str,
    pub summary: String,
}

fn names(rs: &[u32], prefix: &str) -> Vec<String> {
    rs.iter()
        .map(|&r| format!("{prefix}{}", ABI[r as usize]))
        .collect()
}

fn vals(xs: &[String]) -> String {
    format!(
        "[{}]",
        xs.iter()
            .map(|x| format!(".i64 {x}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

/// `Defs.lean`, `manifest.toml` for one function. `callees`: (import name, entry name, callee is pure).
pub fn entry(
    e: &LeanFn,
    out: &Output,
    wat_file: &str,
    prelude: &str,
    callees: &[(String, String, bool)],
) -> Result<(String, String)> {
    let ns = format!("Silmaril.WasmSpec.{}", e.entry);
    let sig = &out.sigs[e.func];
    let wat = &out.modules[e.func];
    let mem = wat.contains("(import \"env\" \"memory\"");
    let args = names(&sig.params, "");
    let res = names(&sig.results, "r_");
    let bv = |xs: &[String]| {
        if xs.is_empty() {
            String::new()
        } else {
            format!("({} : BitVec 64)", xs.join(" "))
        }
    };
    let mut d = String::new();
    writeln!(d, "module\n")?;
    writeln!(d, "public import Silmaril.Wasm.Logic.Tactic.Defs")?;
    writeln!(d, "public import Silmaril.Wasm.Logic.Words.Defs")?;
    writeln!(d, "public import Silmaril.Wasm.Det.NoMem.Module.Defs")?;
    writeln!(d, "public import Silmaril.Wasm.Wat")?;
    for (_, ce, _) in callees {
        writeln!(d, "public import Silmaril.WasmSpec.{ce}.Defs")?;
    }
    writeln!(
        d,
        "\n/-!\n# Wasm specification library: `{}` v1 (generated)\n\nGenerated by `wasm-sim-rv reduce --lean` from the plan contract of the RV64 function\n`{}`: the Wasm problem of its P-locals translation (registers as i64 locals, each instruction\nits simulator method body; see `examples/wasm-sim/rv64/problems/*/reduction.toml` for the\ntransfer back to `Silmaril.RiscV.Ext.MState.step`). Status `stated`: no solution yet.\n-/\n",
        e.entry, e.func
    )?;
    writeln!(d, "@[expose] public section\n\nnamespace {ns}\n")?;
    writeln!(
        d,
        "open Silmaril.Wasm Silmaril.Wasm.Execution Silmaril.Wasm.Execution.Core Silmaril.Wasm.Numerics"
    )?;
    writeln!(
        d,
        "open Silmaril.Wasm.Logic.Core Silmaril.Wasm.Logic.Words\n"
    )?;
    writeln!(
        d,
        "/-- The program, quoted from `{wat_file}`. -/\ndef program := wat3! r#\"\n{wat}\"#\n"
    )?;
    writeln!(
        d,
        "/-- The function `${}` (the module's first function). -/\ndef func : Func := program.funcs[0]\n",
        e.func
    )?;
    if !prelude.trim().is_empty() {
        writeln!(d, "{}\n", prelude.trim())?;
    }
    let mb = if mem { "(B : ByteArray) " } else { "" };
    let mbb = if mem { "(B B' : ByteArray) " } else { "" };
    writeln!(
        d,
        "set_option linter.unusedVariables false in\n/-- The precondition on the entry values of the parameters. -/"
    )?;
    writeln!(d, "def Pre {mb}{} : Prop :=\n  {}\n", bv(&args), e.pre)?;
    writeln!(
        d,
        "set_option linter.unusedVariables false in\n/-- The postcondition on entry values and results. -/"
    )?;
    writeln!(
        d,
        "def Post {mbb}{} {} : Prop :=\n  {}\n",
        bv(&args),
        bv(&res),
        e.post
    )?;
    let (a_s, r_s) = (args.join(" "), res.join(" "));
    let n_res = res.len();
    if !mem {
        writeln!(
            d,
            "/-- **Call-level specification** of the function at address `a`. -/"
        )?;
        writeln!(
            d,
            "def CallSpec {{H : Type}} (P : Profile) (host : HostSemantics H) (a : Nat) : Prop :=\n  FuncSpec P host a (fun _ args => ∃ {a_s}, args = {} ∧ Pre {a_s})\n    (fun s args s' res => s' = s ∧ ∀ {a_s}, args = {} → ∃ {r_s}, res = {} ∧ Post {a_s} {r_s})\n",
            vals(&args),
            vals(&args),
            vals(&res)
        )?;
        writeln!(
            d,
            "/-- The store of the instantiated module (no imports): internal calls (e.g. M-extension\nhelpers) resolve to the module's own functions. -/\ndef store : Store Nat := Silmaril.Wasm.Det.NoMem.instStore program\n"
        )?;
        writeln!(
            d,
            "/-- **Specification** (body level, total correctness, store unchanged), in the instantiated\nmodule. -/"
        )?;
        writeln!(
            d,
            "def Spec : Prop :=\n  ∀ {a_s} : BitVec 64, Pre {a_s} →\n    ∀ (f0 : FuncInst Nat), store.funcs[0]? = some f0 →\n    ∀ (P : Profile) (host : HostSemantics Nat),\n      WP P host store (Frame.forCall f0.module {} func.locals) (expression func.body)\n        (funcPost P host {n_res} fun s' r => s' = store ∧ ∃ {r_s}, r = {} ∧ Post {a_s} {r_s})\n",
            vals(&args),
            vals(&res)
        )?;
    } else {
        writeln!(
            d,
            "/-- **Call-level specification** of the function at address `a`, for memory `ma` of `m`. -/"
        )?;
        writeln!(
            d,
            "def CallSpec {{H : Type}} (P : Profile) (host : HostSemantics H) (Inv : Store H → Prop)\n    (m : ModuleInst) (ma : Nat) (mt : MemoryType) (a : Nat) : Prop :=\n  FuncSpec P host a\n    (fun s args => Inv s ∧ ∃ B {a_s}, MemAt s m ma mt B ∧ args = {} ∧ Pre B {a_s})\n    (fun s args s' res => Inv s' ∧ ∀ B {a_s}, MemAt s m ma mt B → args = {} →\n      ∃ B' {r_s}, MemAt s' m ma mt B' ∧ res = {} ∧ Post B B' {a_s} {r_s})\n",
            vals(&args),
            vals(&args),
            vals(&res)
        )?;
        let binders: Vec<String> = callees.iter().map(|(c, _, _)| format!("a_{c}")).collect();
        writeln!(
            d,
            "/-- **Specification** (body level, total correctness), relative to the callees' `CallSpec`s. -/"
        )?;
        writeln!(
            d,
            "def Spec : Prop :=\n  ∀ {{H : Type}} (P : Profile) (host : HostSemantics H) (Inv : Store H → Prop)\n    (m : ModuleInst) (ma : Nat) (mt : MemoryType){},",
            {
                let n_def = wat.lines().filter(|l| l.starts_with("  (func $")).count();
                let mut b = binders.clone();
                b.extend((1..n_def).map(|k| format!("h{k}")));
                if b.is_empty() {
                    String::new()
                } else {
                    format!(" ({} : Nat)", b.join(" "))
                }
            }
        )?;
        for (i, (c, ce, pure)) in callees.iter().enumerate() {
            let cs = if *pure {
                format!("Silmaril.WasmSpec.{ce}.CallSpec P host a_{c}")
            } else {
                format!("Silmaril.WasmSpec.{ce}.CallSpec P host Inv m ma mt a_{c}")
            };
            writeln!(
                d,
                "    m.funcs[{i}]? = some a_{c} → (∀ s, Inv s → (s.funcs[a_{c}]?).isSome) →\n    {cs} →"
            )?;
        }
        // internal helpers ($ea, M-extension): defined functions 1.. at indices after the imports
        let n_def = wat.lines().filter(|l| l.starts_with("  (func $")).count();
        for k in 1..n_def {
            let idx = callees.len() + k;
            writeln!(
                d,
                "    m.funcs[{idx}]? = some h{k} → (∀ s, Inv s → ∃ fi g, s.funcs[h{k}]? = some fi ∧\n      program.funcs[{k}]? = some g ∧ fi.code = .wasm g ∧ fi.module = m) →"
            )?;
        }
        writeln!(
            d,
            "    ∀ s (B : ByteArray) {a_s}, Inv s → MemAt s m ma mt B → Pre B {a_s} →\n      WP P host s (Frame.forCall m {} func.locals) (expression func.body)\n        (funcPost P host {n_res} fun s' r =>\n          Inv s' ∧ ∃ B' {r_s}, MemAt s' m ma mt B' ∧ r = {} ∧ Post B B' {a_s} {r_s})\n",
            vals(&args),
            vals(&res)
        )?;
    }
    writeln!(d, "end {ns}")?;
    let mut t = String::new();
    writeln!(
        t,
        "# Wasm specification library entry (Silmaril/WasmSpec).\n# Generated by wasm-sim-rv reduce --lean."
    )?;
    writeln!(
        t,
        "schema = 1\nname = \"{}\"\nversion = \"1.0.0\"\nsummary = \"{}\"\nstatus = \"stated\"\n",
        e.entry,
        e.summary.replace('"', "'")
    )?;
    writeln!(
        t,
        "[program]\nkind = \"annotated-wat\"\nsource = \"{wat_file}\"\nlean = \"{ns}.program\"\nmodule = \"{ns}.Defs\"\nfunctions = [\"{}\"]\n",
        e.func
    )?;
    writeln!(
        t,
        "[spec]\nmodule = \"{ns}.Defs\"\nstatements = [\"{ns}.Spec\", \"{ns}.CallSpec\"]"
    )?;
    let desc = if mem {
        "from a store with Inv and memory bytes B satisfying Pre, the body can return results satisfying Post with the final memory bytes B' and Inv, relative to the callees' CallSpecs and to the module's internal helpers resolving to their own code in the module instance"
    } else {
        "in the instantiated module, for all parameter values satisfying Pre, the body can return results satisfying Post without changing the store"
    };
    writeln!(
        t,
        "description = \"\"\"\n`Spec`: {desc}.\nTransfer to RV64: reduction.toml of the plan.\"\"\"\nruns = \"some\"\ncorrectness = \"total\""
    )?;
    for (_, ce, _) in callees {
        writeln!(t, "\n[[dependency]]\nentry = \"{ce}\"\nversion = \"^1\"")?;
    }
    Ok((d, t))
}
