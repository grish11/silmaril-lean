/// A random register-only instruction (all of Ext.Compute).
pub fn compute(r: &mut Rng) -> Inst {
    let (m, kind) = COMPUTE[r.below(COMPUTE.len() as u64) as usize];
    let imm = match m {
        "slli" | "srli" | "srai" => r.below(64) as i64,
        "slliw" | "srliw" | "sraiw" => r.below(32) as i64,
        "lui" | "auipc" => (r.next_u64() as i32 & !0xFFF) as i64,
        _ => (r.below(4096) as i64) - 2048,
    };
    Inst {
        m,
        group: "",
        kind,
        rd: r.reg(),
        rs1: r.reg(),
        rs2: r.reg(),
        imm,
    }
}

pub fn program(seed: u64, cases: usize) -> String {
    let mut r = Rng::new(seed);
    let mut text = String::new();
    let mut data = String::new();
    writeln!(text, "# generated by `wasm-sim-rv gen-rand {seed} {cases}`\n    .option nopic\n    .text\n    .globl _start\n_start:\n    lla sp, stack_top").unwrap();
    for k in 0..cases {
        // initial values
        writeln!(data, "init{k}:").unwrap();
        for _ in 0..31 {
            writeln!(data, "    .dword {:#x}", r.value()).unwrap();
        }
        writeln!(text, "case{k}:\n    lla t6, init{k}").unwrap();
        for i in (1..31).filter(|&i| i != 2) {
            writeln!(text, "    ld x{i}, {}(t6)", 8 * i).unwrap();
        }
        // occasionally make two operands equal, to exercise branches and sub/xor
        let kind = r.below(10);
        match kind {
            0..=5 => {
                let i = compute(&mut r);
                writeln!(
                    text,
                    "    .word {:#010x}  # {} rd=x{} rs1=x{} rs2=x{} imm={}",
                    encode(&i),
                    i.m,
                    i.rd,
                    i.rs1,
                    i.rs2,
                    i.imm
                )
                .unwrap();
            }
            6 | 7 => {
                const L: [(&str, i64); 11] = [
                    ("lb", 1),
                    ("lh", 2),
                    ("lw", 4),
                    ("ld", 8),
                    ("lbu", 1),
                    ("lhu", 2),
                    ("lwu", 4),
                    ("sb", 1),
                    ("sh", 2),
                    ("sw", 4),
                    ("sd", 8),
                ];
                let (m, w) = L[r.below(11) as usize];
                let base = loop {
                    let b = r.reg();
                    if b != 0 {
                        break b;
                    }
                };
                let off = ((r.below(4096) as i64 - 2048) / w) * w;
                writeln!(text, "    lla x{base}, membuf+2048").unwrap();
                let other = r.reg();
                writeln!(text, "    {m} x{other}, {off}(x{base})").unwrap();
            }
            8 => {
                const B: [&str; 6] = ["beq", "bne", "blt", "bge", "bltu", "bgeu"];
                let m = B[r.below(6) as usize];
                let (a, b) = (r.reg(), if r.below(4) == 0 { 0 } else { r.reg() });
                writeln!(text, "    {m} x{a}, x{b}, 1f\n    xori x27, x27, 1\n1:").unwrap();
            }
            _ => {
                let rd = r.reg();
                if r.below(2) == 0 {
                    writeln!(text, "    jal x{rd}, 1f\n    xori x27, x27, 1\n1:").unwrap();
                } else {
                    let imm = r.below(33) as i64 - 16;
                    let delta = -imm + (imm & 1);
                    let rs = loop {
                        let b = r.reg();
                        if b != 0 {
                            break b;
                        }
                    };
                    writeln!(text, "    lla x{rs}, target{k}{:+}\n    jalr x{rd}, {imm}(x{rs})\n    xori x27, x27, 1\ntarget{k}:", delta).unwrap();
                }
            }
        }
        writeln!(text, "    lla t6, regbuf").unwrap();
        for i in 1..31 {
            writeln!(text, "    sd x{i}, {}(t6)", 8 * i).unwrap();
        }
        writeln!(
            text,
            "    li a0, 1\n    mv a1, t6\n    li a2, 256\n    li a7, 64\n    ecall"
        )
        .unwrap();
    }
    writeln!(text, "    li a0, 1\n    lla a1, membuf\n    li a2, 4096\n    li a7, 64\n    ecall\n    li a0, 0\n    li a7, 93\n    ecall").unwrap();
    let mut mem = String::new();
    for _ in 0..512 {
        writeln!(mem, "    .dword {:#x}", r.next_u64()).unwrap();
    }
    format!(
        "{text}\n    .data\n    .balign 8\n{data}membuf:\n{mem}regbuf: .space 256\n    .bss\n    .balign 16\n    .space 4096\nstack_top:\n"
    )
}
