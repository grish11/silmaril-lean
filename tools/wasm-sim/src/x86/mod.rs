use anyhow::{Context, Result};
use std::path::{Path, PathBuf};

pub const NLOCS: i32 = 24;
pub const RIP: i32 = 16;
pub const CF: i32 = 17;
pub const PF: i32 = 18;
pub const AF: i32 = 19;
pub const ZF: i32 = 20;
pub const SF: i32 = 21;
pub const OF: i32 = 22;
pub const DF: i32 = 23;
pub const NAMES: [&str; 24] = [
    "rax", "rcx", "rdx", "rbx", "rsp", "rbp", "rsi", "rdi", "r8", "r9", "r10", "r11", "r12", "r13",
    "r14", "r15", "rip", "cf", "pf", "af", "zf", "sf", "of", "df",
];

pub fn loc_of(name: &str) -> Option<i32> {
    NAMES.iter().position(|n| *n == name).map(|i| i as i32)
}

/// `examples/wasm-sim/x86` relative to the repository root (found from the crate dir).
pub fn x86_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../examples/wasm-sim/x86")
}

pub fn src(f: &str) -> Result<String> {
    let p = x86_dir().join("src").join(f);
    std::fs::read_to_string(&p).with_context(|| format!("reading {}", p.display()))
}

/// Assemble a simulator: header ++ mem-import ++ state ++ core ++ decode.
pub fn sim_source(variant: &str) -> Result<String> {
    Ok(format!(
        ";; GENERATED by `wasm-sim gen-x86` from src/{{header,mem-import,state-{variant},core,decode}}.wat; do not edit.\n{}{}{}{}{})\n",
        src("header.wat")?,
        src("mem-import.wat")?,
        src(&format!("state-{variant}.wat"))?,
        src("core.wat")?,
        src("decode.wat")?
    ))
}

/// Write x86-g.wat and x86-m.wat.
pub fn generate() -> Result<()> {
    for v in ["g", "m"] {
        let p = x86_dir().join(format!("x86-{v}.wat"));
        std::fs::write(&p, sim_source(v)?)?;
        println!("wrote {}", p.display());
    }
    Ok(())
}

pub fn sim_path(variant: &str) -> PathBuf {
    x86_dir().join(format!("x86-{variant}.wat"))
}

/// Simulator module path: `g`, `m`, or a file.
pub fn sim_module_path(sim: &str) -> PathBuf {
    match sim {
        "g" | "m" => sim_path(sim),
        p => PathBuf::from(p),
    }
}

pub const STACK_TOP: u64 = 0x7fff_0000;
pub const STACK_SIZE: u64 = 0x10000;

/// Set up SysV entry: args, stack with the sentinel return address, rip.
pub fn sysv_entry(sim: &mut crate::harness::Sim, entry: u64, args: &[u64]) {
    sysv_entry_at(sim, entry, args, STACK_TOP)
}

/// SysV entry with the stack top at `top` (the sentinel return address is stored at top - 8).
pub fn sysv_entry_at(sim: &mut crate::harness::Sim, entry: u64, args: &[u64], top: u64) {
    const ARGREGS: [i32; 6] = [7, 6, 2, 1, 8, 9];
    for (r, a) in ARGREGS.iter().zip(args) {
        sim.set(*r, *a);
    }
    let sp = top - 8;
    sim.store
        .data_mut()
        .mem
        .store(sp, 8, crate::harness::SENTINEL);
    sim.set(4, sp);
    sim.set(RIP, entry);
}

/// The Lean file holding `wat3!` quotations of the generated simulators.
pub fn lean_quote_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Silmaril/Sim/X86Real/Defs.lean")
}

/// Replace (or, with `check`, compare) the blocks between `-- BEGIN GENERATED: x86-<v>.wat` and
/// `-- END GENERATED` in the Lean file by `def sim<V> : Module := wat3! r#"<text>"#` of the
/// current generated simulator text (`sim_source`, identical to `x86-<v>.wat`).
pub fn lean_quote(check: bool) -> Result<()> {
    let p = lean_quote_path();
    let text = std::fs::read_to_string(&p).with_context(|| format!("reading {}", p.display()))?;
    let mut out = text.clone();
    for v in ["g", "m"] {
        let wat = sim_source(v)?;
        let on_disk = std::fs::read_to_string(sim_path(v))?;
        anyhow::ensure!(
            on_disk == wat,
            "x86-{v}.wat is stale: run `wasm-sim gen-x86`"
        );
        anyhow::ensure!(
            !wat.contains("\"#"),
            "x86-{v}.wat contains the raw-string terminator"
        );
        let begin = format!("-- BEGIN GENERATED: x86-{v}.wat\n");
        let end = "-- END GENERATED\n";
        let i = out
            .find(&begin)
            .with_context(|| format!("no `{}` marker", begin.trim()))?
            + begin.len();
        let j = i + out[i..].find(end).context("no END GENERATED marker")?;
        let block = format!(
            "/-- The simulator `examples/wasm-sim/x86/x86-{v}.wat`, verbatim. -/\ndef sim{} : Module := wat3! r#\"\n{wat}\"#\n",
            v.to_uppercase()
        );
        out.replace_range(i..j, &block);
    }
    if check {
        anyhow::ensure!(
            out == text,
            "{} differs from the generated simulators: run `wasm-sim lean-quote`",
            p.display()
        );
        println!(
            "ok: {} quotes x86-g.wat and x86-m.wat verbatim",
            p.display()
        );
    } else {
        std::fs::write(&p, out)?;
        println!("wrote {}", p.display());
    }
    Ok(())
}
