/// Offset of the code inside the local memory in P-data modules.
pub const PDATA_CODE_OFF: u64 = 0x8000;

/// P-data simulator: memory local to the module (src/mem-local.wat, guest addresses from
/// DATA_BASE), the code bytes in a data segment at DATA_BASE + PDATA_CODE_OFF; decoder included.
pub fn pdata_module(variant: &str, code: &[u8]) -> Result<String> {
    let bytes: String = code.iter().map(|b| format!("\\{b:02x}")).collect();
    Ok(format!(
        ";; P-data {variant} simulator (GENERATED by wasm-sim)\n{}{}{}{}{}  (data (memory $mem) (i32.const {PDATA_CODE_OFF}) \"{bytes}\"))\n",
        super::src("header.wat")?,
        super::src("mem-local.wat")?,
        super::src(&format!("state-{variant}.wat"))?,
        super::src("core.wat")?,
        super::src("decode.wat")?,
    ))
}

fn time<T>(f: impl FnOnce() -> T) -> (T, f64) {
    let t = std::time::Instant::now();
    let r = f();
    (r, t.elapsed().as_secs_f64())
}

fn wasm_size(engine: &Engine, wat: &str) -> Result<(usize, Module)> {
    let bin = wat::parse_str(wat).map_err(|e| anyhow::anyhow!("{e}"))?;
    let m = Module::new(engine, &bin).map_err(|e| anyhow::anyhow!("{e:?}"))?;
    Ok((bin.len(), m))
}

/// Benchmarks on `sum_to(n)` (4 instructions per iteration) and `popcount2` x k.
pub fn bench(n: u64) -> Result<()> {
    let engine = harness::engine();
    let (code, syms) = difftest::assemble_file(&difftest::funcs_path())?;
    let entries: Vec<(String, u64)> = FUNCS
        .iter()
        .map(|f| (f.0.to_string(), CODE_BASE + syms[f.0]))
        .collect();
    let fname = "sum_to";
    let entry = CODE_BASE + syms[fname];
    let mem = || difftest::fresh_mem(&code, &vec![0u8; DATA_LEN]);
    let mut rows = vec![];
    // instruction count from P-mem
    let mut icount = 0u64;
    for v in ["g", "m"] {
        let wat = super::sim_source(v)?;
        let (size, m) = wasm_size(&engine, &wat)?;
        let mut s = Sim::new(&engine, &m, Host::new(Box::new(mem())))?;
        super::sysv_entry_at(&mut s, entry, &[n], DATA_BASE + RSP_OFF);
        let fuel = u64::MAX / 2;
        let (st, t) = time(|| s.run(fuel));
        assert_eq!(st, 1);
        assert_eq!(s.get(0), n.wrapping_mul(n + 1) / 2);
        // count: 3 setup + 3 per iteration + ret, measured by stepping once with fuel
        if icount == 0 {
            let mut s2 = Sim::new(&engine, &m, Host::new(Box::new(mem())))?;
            super::sysv_entry_at(&mut s2, entry, &[1000], DATA_BASE + RSP_OFF);
            let mut c = 0;
            while s2.step() == 0 {
                c += 1;
            }
            icount = (c as u64 - 4) / 1000 * n + 4;
        }
        rows.push((format!("P-mem {}", v.to_uppercase()), size, t));
    }
    // P-data: code in a data segment of the simulator's own memory (src/mem-local.wat)
    for v in ["g", "m"] {
        let wat = pdata_module(v, &code)?;
        let (size, m) = wasm_size(&engine, &wat)?;
        let mut s = Sim::new(
            &engine,
            &m,
            Host::new(Box::new(crate::harness::PageMem::default())),
        )?;
        let e = DATA_BASE + PDATA_CODE_OFF + syms[fname];
        super::sysv_entry_at(&mut s, e, &[n], DATA_BASE + RSP_OFF);
        // the sentinel return address must be written into the module's own memory
        s.call(
            "i_store_i",
            &[8, (DATA_BASE + RSP_OFF - 8) as i64, SENTINEL as i64],
        )?;
        let (st, t) = time(|| s.run(u64::MAX / 2));
        assert_eq!(st, 1, "{:?}", s.fault);
        assert_eq!(s.get(0), n.wrapping_mul(n + 1) / 2);
        rows.push((format!("P-data {}", v.to_uppercase()), size, t));
    }
    for v in ["g", "m"] {
        let sim_wat = super::sim_source(v)?;
        let (ssize, sm) = wasm_size(&engine, &sim_wat)?;
        let prog = program_module(&sm, &code, CODE_BASE, &entries, &Opts::default())?;
        let (psize, pm) = wasm_size(&engine, &prog)?;
        let mut lk = link(&engine, &sm, &pm, Host::new(Box::new(mem())))?;
        super::sysv_entry_at(&mut lk.sim, entry, &[n], DATA_BASE + RSP_OFF);
        let (st, t) = time(|| lk.call(fname));
        assert_eq!(st, 1, "{:?}", lk.sim.fault);
        assert_eq!(lk.sim.get(0), n.wrapping_mul(n + 1) / 2);
        rows.push((
            format!("P-calls {} (2 modules)", v.to_uppercase()),
            ssize + psize,
            t,
        ));
        // wasm-merge'd
        let dir = std::env::temp_dir().join(format!("wasm-sim-bench-{}", std::process::id()));
        std::fs::create_dir_all(&dir)?;
        std::fs::write(dir.join("sim.wasm"), wat::parse_str(&sim_wat)?)?;
        std::fs::write(dir.join("prog.wasm"), wat::parse_str(&prog)?)?;
        let ok = std::process::Command::new("wasm-merge")
            .current_dir(&dir)
            .args(["sim.wasm", "sim", "prog.wasm", "prog", "-o", "merged.wasm"])
            .status()?
            .success();
        if ok {
            for (label, file) in [
                ("wasm-merge", "merged.wasm"),
                ("wasm-merge + wasm-opt -O3", "opt.wasm"),
            ] {
                if file == "opt.wasm" {
                    std::process::Command::new("wasm-opt")
                        .current_dir(&dir)
                        .args(["-O3", "merged.wasm", "-o", "opt.wasm"])
                        .status()?;
                }
                let bin = std::fs::read(dir.join(file))?;
                let mm = Module::new(&engine, &bin).map_err(|e| anyhow::anyhow!("{e:?}"))?;
                let mut s = Sim::new(&engine, &mm, Host::new(Box::new(mem())))?;
                super::sysv_entry_at(&mut s, entry, &[n], DATA_BASE + RSP_OFF);
                let f = s.inst.get_typed_func::<(), i32>(&mut s.store, fname)?;
                let (st, t) = time(|| f.call(&mut s.store, ()));
                assert_eq!(st.map_err(|e| anyhow::anyhow!("{e:?}"))?, 1);
                assert_eq!(s.get(0), n.wrapping_mul(n + 1) / 2);
                rows.push((
                    format!("P-calls {} ({label})", v.to_uppercase()),
                    bin.len(),
                    t,
                ));
            }
        }
        let _ = std::fs::remove_dir_all(&dir);
    }
    if !rows.is_empty() {
        let mm_text = merged_module(&code, CODE_BASE, &entries)?;
        let (size, mm) = wasm_size(&engine, &mm_text)?;
        let mut s = Sim::new(&engine, &mm, Host::new(Box::new(mem())))?;
        super::sysv_entry_at(&mut s, entry, &[n], DATA_BASE + RSP_OFF);
        let f = s.inst.get_typed_func::<(), i32>(&mut s.store, fname)?;
        let (st, t) = time(|| f.call(&mut s.store, ()));
        assert_eq!(st.map_err(|e| anyhow::anyhow!("{e:?}"))?, 1);
        rows.push(("P-calls G (textual merge, no decoder)".into(), size, t));
    }
    println!("sum_to({n}): {icount} x86 instructions");
    println!(
        "{:<40} {:>10} {:>10} {:>12}",
        "variant", "wasm B", "time s", "Minsn/s"
    );
    for (l, sz, t) in rows {
        println!(
            "{l:<40} {sz:>10} {t:>10.3} {:>12.1}",
            icount as f64 / t / 1e6
        );
    }
    Ok(())
}
