//! P-calls translator: x86-64 machine code -> a Wasm program that drives the simulator through
//! its method API (`i_*`, `ea`, `cond`, `get`/`set`).
//!
//! Each x86 function (entry and every direct `call` target) becomes a Wasm function
//! `$f_<addr> (result i32)` returning a status; its basic blocks are dispatched by a
//! `loop` + `br_table` on a block-index local. Fall-through between blocks in address order is
//! free (nested `block`s); jumps set the index and `br` to the loop head. Every instruction is a
//! method call followed by `i_next(len)`, so the simulator's rip is exact after every
//! instruction (rip-relative addresses are folded to constants by the translator).
//!
//! Output modes:
//! * `program`: a module importing the methods from module `sim` (link with a G or M simulator);
//! * `merged`: one module = G simulator (without decoder) + the program (textual merge).
//!
//! Closed problems and per-function split modules are generated by `wasm-sim problems`
//! (`super::problem`; see `examples/wasm-sim/x86/problems/README.md`).

