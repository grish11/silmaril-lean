const R64: [Register; 16] = [
    Register::RAX,
    Register::RCX,
    Register::RDX,
    Register::RBX,
    Register::RSP,
    Register::RBP,
    Register::RSI,
    Register::RDI,
    Register::R8,
    Register::R9,
    Register::R10,
    Register::R11,
    Register::R12,
    Register::R13,
    Register::R14,
    Register::R15,
];

/// Register -> (code, width in bytes). Codes 16..19 = ah ch dh bh.
fn reg(r: Register) -> Result<(i32, i32)> {
    let hi = [Register::AH, Register::CH, Register::DH, Register::BH];
    if let Some(i) = hi.iter().position(|x| *x == r) {
        return Ok((16 + i as i32, 1));
    }
    let f = r.full_register();
    let Some(i) = R64.iter().position(|x| *x == f) else {
        bail!("register {r:?} not modelled")
    };
    Ok((i as i32, r.size() as i32))
}

fn regcode(r: Register) -> i32 {
    if r == Register::None {
        -1
    } else {
        R64.iter()
            .position(|x| *x == r)
            .map(|i| i as i32)
            .unwrap_or(-2)
    }
}

/// The address expression of the memory operand.
fn ea(ins: &Instruction) -> Result<String> {
    if ins.is_ip_rel_memory_operand() {
        return Ok(format!(
            "(i64.const {})",
            ins.ip_rel_memory_address() as i64
        ));
    }
    let (b, i) = (regcode(ins.memory_base()), regcode(ins.memory_index()));
    if b == -2 || i == -2 || ins.segment_prefix() != Register::None {
        bail!("unsupported memory operand in {ins}");
    }
    let s = ins.memory_index_scale().trailing_zeros();
    Ok(format!(
        "(call $ea (i32.const {b}) (i32.const {i}) (i32.const {s}) (i64.const {}))",
        ins.memory_displacement64() as i64
    ))
}

fn cc(ins: &Instruction) -> i32 {
    ins.condition_code() as i32 - ConditionCode::o as i32
}

fn is_imm(k: OpKind) -> bool {
    matches!(
        k,
        OpKind::Immediate8
            | OpKind::Immediate16
            | OpKind::Immediate32
            | OpKind::Immediate64
            | OpKind::Immediate8to16
            | OpKind::Immediate8to32
            | OpKind::Immediate8to64
            | OpKind::Immediate32to64
    )
}

/// A decoded function: instructions by address, block leaders, callees.
pub struct Func {
    pub entry: u64,
    pub insns: BTreeMap<u64, Instruction>,
    pub leaders: BTreeSet<u64>,
    pub callees: BTreeSet<u64>,
}

pub fn decode_func(code: &[u8], base: u64, entry: u64) -> Result<Func> {
    let mut f = Func {
        entry,
        insns: BTreeMap::new(),
        leaders: BTreeSet::from([entry]),
        callees: BTreeSet::new(),
    };
    let mut work = vec![entry];
    while let Some(a) = work.pop() {
        if f.insns.contains_key(&a) {
            continue;
        }
        if a < base || a >= base + code.len() as u64 {
            bail!("control reaches {a:#x} outside the code");
        }
        let mut d = Decoder::with_ip(64, &code[(a - base) as usize..], a, DecoderOptions::NONE);
        let ins = d.decode();
        if ins.is_invalid() {
            bail!("invalid instruction at {a:#x}");
        }
        f.insns.insert(a, ins);
        let next = ins.next_ip();
        match ins.flow_control() {
            FlowControl::Next | FlowControl::Call => {
                if ins.flow_control() == FlowControl::Call {
                    if ins.op0_kind() != OpKind::NearBranch64 {
                        bail!("indirect call at {a:#x} not supported");
                    }
                    f.callees.insert(ins.near_branch_target());
                }
                work.push(next);
            }
            FlowControl::ConditionalBranch => {
                f.leaders.insert(ins.near_branch_target());
                f.leaders.insert(next);
                work.push(ins.near_branch_target());
                work.push(next);
            }
            FlowControl::UnconditionalBranch => {
                f.leaders.insert(ins.near_branch_target());
                work.push(ins.near_branch_target());
                f.leaders.insert(next);
            }
            FlowControl::Return => {
                f.leaders.insert(next);
            }
            FlowControl::Interrupt if ins.mnemonic() == Mnemonic::Syscall => work.push(next),
            fc => bail!("unsupported control flow {fc:?} at {a:#x}: {ins}"),
        }
    }
    f.leaders.retain(|l| f.insns.contains_key(l));
    Ok(f)
}

/// Translation options.
#[derive(Clone, Default)]
pub struct Opts {
    /// call `trace.insn(addr)` and `trace.val(loc value)` x24 before every instruction
    pub trace: bool,
}

/// Translate one instruction (not control flow); returns WAT and records used methods.
fn insn(ins: &Instruction, used: &mut BTreeSet<&'static str>) -> Result<String> {
    use Mnemonic as M;
    let m = ins.mnemonic();
    let k0 = if ins.op_count() > 0 {
        ins.op0_kind()
    } else {
        OpKind::Register
    };
    let k1 = if ins.op_count() > 1 {
        ins.op1_kind()
    } else {
        OpKind::Register
    };
    let alu = match m {
        M::Add => Some(0),
        M::Or => Some(1),
        M::Adc => Some(2),
        M::Sbb => Some(3),
        M::And => Some(4),
        M::Sub => Some(5),
        M::Xor => Some(6),
        M::Cmp => Some(7),
        M::Test => Some(8),
        _ => None,
    };
    let msize = || ins.memory_size().size() as i32;
    let mut u = |n: &'static str| {
        used.insert(n);
    };
    let s = if let Some(op) = alu {
        match (k0, k1) {
            (OpKind::Register, OpKind::Register) => {
                let ((d, w), (s, _)) = (reg(ins.op0_register())?, reg(ins.op1_register())?);
                u("i_alu_rr");
                format!(
                    "(call $i_alu_rr (i32.const {op}) (i32.const {w}) (i32.const {d}) (i32.const {s}))"
                )
            }
            (OpKind::Register, k) if is_imm(k) => {
                let (d, w) = reg(ins.op0_register())?;
                u("i_alu_ri");
                format!(
                    "(call $i_alu_ri (i32.const {op}) (i32.const {w}) (i32.const {d}) (i64.const {}))",
                    ins.immediate(1) as i64
                )
            }
            (OpKind::Register, OpKind::Memory) => {
                let (d, w) = reg(ins.op0_register())?;
                u("i_alu_rm");
                u("ea");
                format!(
                    "(call $i_alu_rm (i32.const {op}) (i32.const {w}) (i32.const {d}) {})",
                    ea(ins)?
                )
            }
            (OpKind::Memory, OpKind::Register) => {
                let (s, w) = reg(ins.op1_register())?;
                u("i_alu_mr");
                u("ea");
                format!(
                    "(call $i_alu_mr (i32.const {op}) (i32.const {w}) {} (i32.const {s}))",
                    ea(ins)?
                )
            }
            (OpKind::Memory, k) if is_imm(k) => {
                u("i_alu_mi");
                u("ea");
                format!(
                    "(call $i_alu_mi (i32.const {op}) (i32.const {}) {} (i64.const {}))",
                    msize(),
                    ea(ins)?,
                    ins.immediate(1) as i64
                )
            }
            _ => bail!("unsupported operands: {ins}"),
        }
    } else {
        match m {
            M::Nop | M::Endbr64 => String::new(),
            M::Mov => match (k0, k1) {
                (OpKind::Register, OpKind::Register) => {
                    let ((d, w), (s, _)) = (reg(ins.op0_register())?, reg(ins.op1_register())?);
                    u("i_mov_rr");
                    format!("(call $i_mov_rr (i32.const {w}) (i32.const {d}) (i32.const {s}))")
                }
                (OpKind::Register, k) if is_imm(k) => {
                    let (d, w) = reg(ins.op0_register())?;
                    u("i_mov_ri");
                    format!(
                        "(call $i_mov_ri (i32.const {w}) (i32.const {d}) (i64.const {}))",
                        ins.immediate(1) as i64
                    )
                }
                (OpKind::Register, OpKind::Memory) => {
                    let (d, w) = reg(ins.op0_register())?;
                    u("i_load");
                    u("ea");
                    format!(
                        "(call $i_load (i32.const {w}) (i32.const {d}) {})",
                        ea(ins)?
                    )
                }
                (OpKind::Memory, OpKind::Register) => {
                    let (s, w) = reg(ins.op1_register())?;
                    u("i_store");
                    u("ea");
                    format!(
                        "(call $i_store (i32.const {w}) {} (i32.const {s}))",
                        ea(ins)?
                    )
                }
                (OpKind::Memory, k) if is_imm(k) => {
                    u("i_store_i");
                    u("ea");
                    format!(
                        "(call $i_store_i (i32.const {}) {} (i64.const {}))",
                        msize(),
                        ea(ins)?,
                        ins.immediate(1) as i64
                    )
                }
                _ => bail!("unsupported operands: {ins}"),
            },
            M::Movzx | M::Movsx | M::Movsxd => {
                let sx = (m != M::Movzx) as i32;
                let (d, w) = reg(ins.op0_register())?;
                if k1 == OpKind::Register {
                    let (s, sw) = reg(ins.op1_register())?;
                    u("i_movx_rr");
                    format!(
                        "(call $i_movx_rr (i32.const {sx}) (i32.const {w}) (i32.const {sw}) (i32.const {d}) (i32.const {s}))"
                    )
                } else {
                    u("i_movx_rm");
                    u("ea");
                    format!(
                        "(call $i_movx_rm (i32.const {sx}) (i32.const {w}) (i32.const {}) (i32.const {d}) {})",
                        msize(),
                        ea(ins)?
                    )
                }
            }
            M::Lea => {
                let (d, w) = reg(ins.op0_register())?;
                u("i_lea");
                u("ea");
                format!("(call $i_lea (i32.const {w}) (i32.const {d}) {})", ea(ins)?)
            }
            M::Bswap => {
                let (d, w) = reg(ins.op0_register())?;
                if w == 2 {
                    bail!("bswap r16 is undefined");
                }
                u("i_bswap_r");
                format!("(call $i_bswap_r (i32.const {w}) (i32.const {d}))")
            }
            M::Inc | M::Dec | M::Not | M::Neg => {
                let op = match m {
                    M::Inc => 0,
                    M::Dec => 1,
                    M::Not => 2,
                    _ => 3,
                };
                if k0 == OpKind::Register {
                    let (d, w) = reg(ins.op0_register())?;
                    u("i_unary_r");
                    format!("(call $i_unary_r (i32.const {op}) (i32.const {w}) (i32.const {d}))")
                } else {
                    u("i_unary_m");
                    u("ea");
                    format!(
                        "(call $i_unary_m (i32.const {op}) (i32.const {}) {})",
                        msize(),
                        ea(ins)?
                    )
                }
            }
            M::Shl | M::Shr | M::Sar | M::Rol | M::Ror => {
                let op = match m {
                    M::Rol => 0,
                    M::Ror => 1,
                    M::Shl => 4,
                    M::Shr => 5,
                    _ => 7,
                };
                let by_cl = k1 == OpKind::Register;
                let n = if by_cl { 0 } else { ins.immediate(1) as i32 };
                if k0 == OpKind::Register {
                    let (d, w) = reg(ins.op0_register())?;
                    if by_cl {
                        u("i_shift_rcl");
                        format!(
                            "(call $i_shift_rcl (i32.const {op}) (i32.const {w}) (i32.const {d}))"
                        )
                    } else {
                        u("i_shift_ri");
                        format!(
                            "(call $i_shift_ri (i32.const {op}) (i32.const {w}) (i32.const {d}) (i32.const {n}))"
                        )
                    }
                } else if by_cl {
                    u("i_shift_mcl");
                    u("ea");
                    format!(
                        "(call $i_shift_mcl (i32.const {op}) (i32.const {}) {})",
                        msize(),
                        ea(ins)?
                    )
                } else {
                    u("i_shift_mi");
                    u("ea");
                    format!(
                        "(call $i_shift_mi (i32.const {op}) (i32.const {}) {} (i32.const {n}))",
                        msize(),
                        ea(ins)?
                    )
                }
            }
            M::Xchg => match (k0, k1) {
                (OpKind::Register, OpKind::Register) => {
                    let ((a, w), (b, _)) = (reg(ins.op0_register())?, reg(ins.op1_register())?);
                    u("i_xchg_rr");
                    format!("(call $i_xchg_rr (i32.const {w}) (i32.const {a}) (i32.const {b}))")
                }
                (OpKind::Memory, OpKind::Register) | (OpKind::Register, OpKind::Memory) => {
                    let r = if k0 == OpKind::Register {
                        ins.op0_register()
                    } else {
                        ins.op1_register()
                    };
                    let (r, w) = reg(r)?;
                    u("i_xchg_rm");
                    u("ea");
                    format!(
                        "(call $i_xchg_rm (i32.const {w}) (i32.const {r}) {})",
                        ea(ins)?
                    )
                }
                _ => bail!("unsupported operands: {ins}"),
            },
            M::Popcnt | M::Tzcnt | M::Lzcnt | M::Bsf | M::Bsr => {
                let op = match m {
                    M::Popcnt => 0,
                    M::Tzcnt => 1,
                    M::Lzcnt => 2,
                    M::Bsf => 3,
                    _ => 4,
                };
                let (d, w) = reg(ins.op0_register())?;
                if k1 == OpKind::Register {
                    u("i_bit_rr");
                    format!(
                        "(call $i_bit_rr (i32.const {op}) (i32.const {w}) (i32.const {d}) (i32.const {}))",
                        reg(ins.op1_register())?.0
                    )
                } else {
                    u("i_bit_rm");
                    u("ea");
                    format!(
                        "(call $i_bit_rm (i32.const {op}) (i32.const {w}) (i32.const {d}) {})",
                        ea(ins)?
                    )
                }
            }
            M::Imul if ins.op_count() == 2 && k1 == OpKind::Register => {
                let ((d, w), (s, _)) = (reg(ins.op0_register())?, reg(ins.op1_register())?);
                u("i_imul_rr");
                format!("(call $i_imul_rr (i32.const {w}) (i32.const {d}) (i32.const {s}))")
            }
            M::Imul if ins.op_count() == 2 => {
                let (d, w) = reg(ins.op0_register())?;
                u("i_imul_rm");
                u("ea");
                format!(
                    "(call $i_imul_rm (i32.const {w}) (i32.const {d}) {})",
                    ea(ins)?
                )
            }
            M::Imul if ins.op_count() == 3 && k1 == OpKind::Register => {
                let ((d, w), (s, _)) = (reg(ins.op0_register())?, reg(ins.op1_register())?);
                u("i_imul_rri");
                format!(
                    "(call $i_imul_rri (i32.const {w}) (i32.const {d}) (i32.const {s}) (i64.const {}))",
                    ins.immediate(2) as i64
                )
            }
            M::Imul if ins.op_count() == 3 => {
                let (d, w) = reg(ins.op0_register())?;
                u("i_imul_rmi");
                u("ea");
                format!(
                    "(call $i_imul_rmi (i32.const {w}) (i32.const {d}) {} (i64.const {}))",
                    ea(ins)?,
                    ins.immediate(2) as i64
                )
            }
            M::Mul | M::Imul | M::Div | M::Idiv if ins.op_count() == 1 => {
                let op = match m {
                    M::Mul => 4,
                    M::Imul => 5,
                    M::Div => 6,
                    _ => 7,
                };
                if k0 == OpKind::Register {
                    let (s, w) = reg(ins.op0_register())?;
                    if w < 4 {
                        bail!("8/16-bit mul/div not supported: {ins}");
                    }
                    u("i_muldiv_r");
                    format!(
                        "(local.set $s (call $i_muldiv_r (i32.const {op}) (i32.const {w}) (i32.const {s}))) (if (local.get $s) (then (return (local.get $s))))"
                    )
                } else {
                    if msize() < 4 {
                        bail!("8/16-bit mul/div not supported: {ins}");
                    }
                    u("i_muldiv_m");
                    u("ea");
                    format!(
                        "(local.set $s (call $i_muldiv_m (i32.const {op}) (i32.const {}) {})) (if (local.get $s) (then (return (local.get $s))))",
                        msize(),
                        ea(ins)?
                    )
                }
            }
            M::Push if k0 == OpKind::Memory => {
                u("i_push_m");
                u("ea");
                format!("(call $i_push_m {})", ea(ins)?)
            }
            M::Pause => String::new(),
            M::Cbw => {
                u("i_cxx");
                "(call $i_cxx (i32.const 152) (i32.const 2))".into()
            }
            M::Cwd => {
                u("i_cxx");
                "(call $i_cxx (i32.const 153) (i32.const 2))".into()
            }
            M::Cdqe | M::Cwde => {
                u("i_cxx");
                format!(
                    "(call $i_cxx (i32.const 152) (i32.const {}))",
                    if m == M::Cdqe { 8 } else { 4 }
                )
            }
            M::Cqo | M::Cdq => {
                u("i_cxx");
                format!(
                    "(call $i_cxx (i32.const 153) (i32.const {}))",
                    if m == M::Cqo { 8 } else { 4 }
                )
            }
            M::Push if k0 == OpKind::Register => {
                u("i_push_r");
                format!(
                    "(call $i_push_r (i32.const {}))",
                    reg(ins.op0_register())?.0
                )
            }
            M::Push if is_imm(k0) => {
                u("i_push_i");
                format!("(call $i_push_i (i64.const {}))", ins.immediate(0) as i64)
            }
            M::Pop if k0 == OpKind::Register => {
                u("i_pop_r");
                format!("(call $i_pop_r (i32.const {}))", reg(ins.op0_register())?.0)
            }
            M::Cmovo
            | M::Cmovno
            | M::Cmovb
            | M::Cmovae
            | M::Cmove
            | M::Cmovne
            | M::Cmovbe
            | M::Cmova
            | M::Cmovs
            | M::Cmovns
            | M::Cmovp
            | M::Cmovnp
            | M::Cmovl
            | M::Cmovge
            | M::Cmovle
            | M::Cmovg => {
                let (d, w) = reg(ins.op0_register())?;
                if k1 == OpKind::Register {
                    u("i_cmov_rr");
                    format!(
                        "(call $i_cmov_rr (i32.const {}) (i32.const {w}) (i32.const {d}) (i32.const {}))",
                        cc(ins),
                        reg(ins.op1_register())?.0
                    )
                } else {
                    u("i_cmov_rm");
                    u("ea");
                    format!(
                        "(call $i_cmov_rm (i32.const {}) (i32.const {w}) (i32.const {d}) {})",
                        cc(ins),
                        ea(ins)?
                    )
                }
            }
            M::Seto
            | M::Setno
            | M::Setb
            | M::Setae
            | M::Sete
            | M::Setne
            | M::Setbe
            | M::Seta
            | M::Sets
            | M::Setns
            | M::Setp
            | M::Setnp
            | M::Setl
            | M::Setge
            | M::Setle
            | M::Setg => {
                if k0 == OpKind::Register {
                    u("i_setcc_r");
                    format!(
                        "(call $i_setcc_r (i32.const {}) (i32.const {}))",
                        cc(ins),
                        reg(ins.op0_register())?.0
                    )
                } else {
                    u("i_setcc_m");
                    u("ea");
                    format!("(call $i_setcc_m (i32.const {}) {})", cc(ins), ea(ins)?)
                }
            }
            _ => bail!("unsupported instruction {ins} at {:#x}", ins.ip()),
        }
    };
    Ok(s)
}

/// Translate one function to a WAT function `$f_<entry>`.
pub fn translate_func(f: &Func, opts: &Opts, used: &mut BTreeSet<&'static str>) -> Result<String> {
    let blocks: Vec<u64> = f.leaders.iter().copied().collect();
    let bidx = |a: u64| blocks.iter().position(|b| *b == a);
    let mut w = String::new();
    writeln!(
        w,
        "  ;; x86 function at {:#x}: {} instructions, {} blocks",
        f.entry,
        f.insns.len(),
        blocks.len()
    )?;
    writeln!(w, "  (func $f_{:x} (result i32)", f.entry)?;
    writeln!(w, "    (local $b i32) (local $s i32)")?;
    writeln!(w, "    (loop $d")?;
    for k in (0..blocks.len()).rev() {
        writeln!(w, "    (block $B{k}")?;
    }
    let labels: Vec<String> = (0..blocks.len()).map(|k| format!("$B{k}")).collect();
    writeln!(
        w,
        "      (br_table {} $B{} (local.get $b)))",
        labels.join(" "),
        blocks.len() - 1
    )?;
    let next_ = |used: &mut BTreeSet<&'static str>, ins: &Instruction| {
        used.insert("i_next");
        format!("(call $i_next (i32.const {}))", ins.len())
    };
    for (k, &start) in blocks.iter().enumerate() {
        writeln!(w, "      ;; @block {k} {start:#x}")?;
        let end = blocks.get(k + 1).copied().unwrap_or(u64::MAX);
        let mut ended = false;
        for (&a, ins) in f.insns.range(start..end) {
            if opts.trace {
                used.insert("snap");
                writeln!(w, "      (call $snap (i64.const {a}))")?;
            }
            let goto = |t: u64| -> Result<String> {
                let Some(j) = bidx(t) else {
                    bail!("jump to {t:#x} leaves the function")
                };
                Ok(format!("(local.set $b (i32.const {j})) (br $d)"))
            };
            let line = match ins.flow_control() {
                FlowControl::UnconditionalBranch => {
                    if ins.op0_kind() != OpKind::NearBranch64 {
                        bail!("indirect jmp at {a:#x} not supported");
                    }
                    used.insert("i_jmp");
                    ended = true;
                    format!(
                        "(call $i_jmp (i64.const {})) {}",
                        ins.near_branch_target() as i64,
                        goto(ins.near_branch_target())?
                    )
                }
                FlowControl::ConditionalBranch => {
                    used.insert("i_jmp");
                    used.insert("cond");
                    format!(
                        "{} (if (call $cond (i32.const {})) (then (call $i_jmp (i64.const {})) {}))",
                        next_(used, ins),
                        cc(ins),
                        ins.near_branch_target() as i64,
                        goto(ins.near_branch_target())?
                    )
                }
                FlowControl::Call => {
                    used.insert("i_call");
                    used.insert("get");
                    let t = ins.near_branch_target();
                    format!(
                        "{} (call $i_call (i64.const {})) (local.set $s (call $f_{t:x})) (if (local.get $s) (then (return (local.get $s)))) (if (i64.ne (call $get (i32.const 16)) (i64.const {})) (then (return (i32.const 2))))",
                        next_(used, ins),
                        t as i64,
                        ins.next_ip() as i64
                    )
                }
                FlowControl::Return => {
                    if ins.op_count() != 0 {
                        bail!("ret imm16 not supported");
                    }
                    used.insert("i_ret");
                    ended = true;
                    "(call $i_ret) (return (i32.const 0))".to_string()
                }
                _ if ins.mnemonic() == Mnemonic::Syscall => {
                    used.insert("i_syscall");
                    format!(
                        "{} (local.set $s (call $i_syscall)) (if (local.get $s) (then (return (local.get $s))))",
                        next_(used, ins)
                    )
                }
                _ => {
                    let body = insn(ins, used)?;
                    format!("{body} {}", next_(used, ins))
                }
            };
            writeln!(w, "      ;; {a:#x}: {ins}\n      {}", line.trim())?;
        }
        if !ended && end == u64::MAX {
            writeln!(w, "      (return (i32.const 2))")?;
        }
        writeln!(w, "    )")?;
    }
    writeln!(w, "    (unreachable))")?;
    Ok(w)
}

/// All functions reachable from the entries.
pub fn decode_all(code: &[u8], base: u64, entries: &[u64]) -> Result<Vec<Func>> {
    let mut seen = BTreeSet::new();
    let mut work: Vec<u64> = entries.to_vec();
    let mut out = vec![];
    while let Some(e) = work.pop() {
        if !seen.insert(e) {
            continue;
        }
        let f = decode_func(code, base, e)?;
        work.extend(f.callees.iter().copied());
        out.push(f);
    }
    out.sort_by_key(|f| f.entry);
    Ok(out)
}

/// The program functions (+ exported entry wrappers `name -> status`) for the given entries.
pub fn program_body(
    funcs: &[Func],
    entries: &[(String, u64)],
    opts: &Opts,
    used: &mut BTreeSet<&'static str>,
) -> Result<String> {
    let mut w = String::new();
    for f in funcs {
        w += &translate_func(f, opts, used)?;
    }
    for (name, e) in entries {
        used.insert("get");
        writeln!(
            w,
            "  ;; entry `{name}`: status 1 iff the function returned to the sentinel\n  (func $run_{name} (export \"{name}\") (result i32) (local $s i32)\n    (local.set $s (call $f_{e:x}))\n    (if (local.get $s) (then (return (local.get $s))))\n    (if (result i32) (i64.eq (call $get (i32.const 16)) (i64.const {})) (then (i32.const 1)) (else (i32.const 2))))",
            SENTINEL as i64
        )?;
    }
    if opts.trace {
        used.insert("get");
        writeln!(
            w,
            "  (func $snap (param $a i64) (local $l i32)\n    (call $trace_insn (local.get $a))\n    (loop $l\n      (call $trace_val (call $get (local.get $l)))\n      (local.set $l (i32.add (local.get $l) (i32.const 1)))\n      (br_if $l (i32.lt_u (local.get $l) (i32.const {NLOCS})))))"
        )?;
    }
    Ok(w)
}

/// Import declarations for the used methods, with types from the simulator module.
fn imports(sim: &Module, used: &BTreeSet<&'static str>, trace: bool) -> Result<String> {
    let mut w = String::new();
    for n in used {
        if *n == "snap" {
            continue;
        }
        let ty = sim
            .get_export(n)
            .with_context(|| format!("simulator lacks export {n}"))?;
        let wasmtime::ExternType::Func(ft) = ty else {
            bail!("{n} is not a function")
        };
        let ps: Vec<String> = ft.params().map(|t| format!("{t}")).collect();
        let rs: Vec<String> = ft.results().map(|t| format!("{t}")).collect();
        let mut sig = String::new();
        if !ps.is_empty() {
            sig += &format!(" (param {})", ps.join(" "));
        }
        if !rs.is_empty() {
            sig += &format!(" (result {})", rs.join(" "));
        }
        writeln!(w, "  (import \"sim\" \"{n}\" (func ${n}{sig}))")?;
    }
    if trace {
        writeln!(
            w,
            "  (import \"trace\" \"insn\" (func $trace_insn (param i64)))"
        )?;
        writeln!(
            w,
            "  (import \"trace\" \"val\" (func $trace_val (param i64)))"
        )?;
    }
    Ok(w)
}

/// Standalone program module (imports the simulator as `sim`).
pub fn program_module(
    sim: &Module,
    code: &[u8],
    base: u64,
    entries: &[(String, u64)],
    opts: &Opts,
) -> Result<String> {
    let funcs = decode_all(code, base, &entries.iter().map(|e| e.1).collect::<Vec<_>>())?;
    let mut used = BTreeSet::new();
    let body = program_body(&funcs, entries, opts, &mut used)?;
    Ok(format!(
        ";; P-calls program GENERATED by `wasm-sim pcalls`\n(module\n{}{body})\n",
        imports(sim, &used, opts.trace)?
    ))
}

/// G simulator without decoder + program, one module (textual merge).
pub fn merged_module(code: &[u8], base: u64, entries: &[(String, u64)]) -> Result<String> {
    let funcs = decode_all(code, base, &entries.iter().map(|e| e.1).collect::<Vec<_>>())?;
    let mut used = BTreeSet::new();
    let body = program_body(&funcs, entries, &Opts::default(), &mut used)?;
    Ok(format!(
        ";; G simulator (no decoder) + P-calls program, GENERATED by `wasm-sim pcalls --mode merged`\n{}{}{}{}  ;; ---- program\n{body})\n",
        super::src("header.wat")?,
        super::src("mem-import.wat")?,
        super::src("state-g.wat")?,
        super::src("core.wat")?
    ))
}

#[derive(clap::Args)]
pub struct Args {
    /// .S file (assembled with GNU as) or raw code (.bin, with --base)
    #[arg(long)]
    src: Option<PathBuf>,
    /// function names (symbols of the .S); default: all functions of the spec file / funcs.S
    #[arg(long, value_delimiter = ',')]
    func: Vec<String>,
    /// program | merged (closed problems and split modules: `wasm-sim problems`)
    #[arg(long, default_value = "program")]
    mode: String,
    /// output file
    #[arg(long, short)]
    out: PathBuf,
    /// emit trace calls (program mode)
    #[arg(long)]
    trace: bool,
}

pub fn main(a: Args) -> Result<()> {
    let src = a.src.clone().unwrap_or_else(difftest::funcs_path);
    let (code, syms) = difftest::assemble_file(&src)?;
    let names: Vec<String> = if a.func.is_empty() {
        FUNCS.iter().map(|f| f.0.to_string()).collect()
    } else {
        a.func.clone()
    };
    let entries: Vec<(String, u64)> = names
        .iter()
        .map(|n| {
            Ok((
                n.clone(),
                CODE_BASE + *syms.get(n).with_context(|| format!("no symbol {n}"))?,
            ))
        })
        .collect::<Result<_>>()?;
    match a.mode.as_str() {
        "program" => {
            let engine = harness::engine();
            let sim = harness::load_module(&engine, &super::sim_path("g"))?;
            std::fs::write(
                &a.out,
                program_module(&sim, &code, CODE_BASE, &entries, &Opts { trace: a.trace })?,
            )?;
        }
        "merged" => std::fs::write(&a.out, merged_module(&code, CODE_BASE, &entries)?)?,
        m => bail!("unknown mode {m}"),
    }
    Ok(())
}

// ------------------------------------------------------------------ running P-calls

/// A simulator instance plus a linked program instance in the same store.
pub struct Linked {
    pub sim: Sim,
    pub prog: wasmtime::Instance,
}

pub fn link(engine: &Engine, sim_m: &Module, prog_m: &Module, host: Host) -> Result<Linked> {
    let mut linker = Linker::new(engine);
    harness::add_env(&mut linker)?;
    let mut store = Store::new(engine, host);
    let si = linker.instantiate(&mut store, sim_m)?;
    linker.instance(&mut store, "sim", si)?;
    let pi = linker.instantiate(&mut store, prog_m)?;
    Ok(Linked {
        sim: Sim::from_instance(store, si)?,
        prog: pi,
    })
}

impl Linked {
    pub fn call(&mut self, name: &str) -> i32 {
        let f = self
            .prog
            .get_typed_func::<(), i32>(&mut self.sim.store, name)
            .expect("entry");
        match f.call(&mut self.sim.store, ()) {
            Ok(s) => s,
            Err(e) => {
                self.sim.fault = Some(format!("{e:#}"));
                harness::ST_FAULT
            }
        }
    }
}

/// Lockstep: P-calls program (traced) over simulator `sim_m` vs P-mem `step` of the same
/// simulator, comparing all locations before every instruction and memory at the end.
pub fn lockstep(
    engine: &Engine,
    sim_m: &Module,
    code: &[u8],
    syms: &BTreeMap<String, u64>,
    funcs: &[(&str, &[difftest::Arg])],
    per: usize,
    seed: u64,
) -> Result<()> {
    // functions the translator rejects (e.g. indirect jumps) are reported and skipped
    let mut ok_funcs = vec![];
    for f in funcs {
        match decode_all(code, CODE_BASE, &[CODE_BASE + syms[f.0]]).and_then(|fs| {
            let mut u = BTreeSet::new();
            fs.iter()
                .try_for_each(|x| translate_func(x, &Opts::default(), &mut u).map(|_| ()))
        }) {
            Ok(()) => ok_funcs.push(*f),
            Err(e) => println!("P-calls: skipping {}: {e}", f.0),
        }
    }
    let funcs = &ok_funcs[..];
    let entries: Vec<(String, u64)> = funcs
        .iter()
        .map(|f| (f.0.to_string(), CODE_BASE + syms[f.0]))
        .collect();
    let text = program_module(sim_m, code, CODE_BASE, &entries, &Opts { trace: true })?;
    let prog_m = Module::new(engine, &text).map_err(|e| anyhow::anyhow!("{e:?}"))?;
    let mut rng = Rng(seed ^ 0x5eed);
    let (mut steps, mut fails) = (0u64, 0);
    for (name, kinds) in funcs {
        let entry = CODE_BASE + syms[*name];
        for _ in 0..per {
            let mut fill: Vec<u8> = (0..DATA_LEN).map(|_| rng.next_u64() as u8).collect();
            let args = difftest::gen_args(&mut rng, kinds, DATA_BASE, &mut fill);
            let useed = rng.next_u64();
            let mk_host = || {
                let mut h = Host::new(Box::new(difftest::fresh_mem(code, &fill)));
                h.undef = Undef::Random(useed);
                h
            };
            let mut lk = link(engine, sim_m, &prog_m, mk_host())?;
            super::sysv_entry_at(&mut lk.sim, entry, &args, DATA_BASE + RSP_OFF);
            let st_c = lk.call(name);
            let mut pm = Sim::new(engine, sim_m, mk_host())?;
            super::sysv_entry_at(&mut pm, entry, &args, DATA_BASE + RSP_OFF);
            let tr = std::mem::take(&mut lk.sim.store.data_mut().trace);
            let mut ok = true;
            for (i, snap) in tr.chunks(1 + NLOCS as usize).enumerate() {
                let st: Vec<u64> = (0..NLOCS).map(|l| pm.get(l)).collect();
                if snap[0] != st[RIP as usize] || snap[1..] != st[..] {
                    println!(
                        "DIVERGE {name}{args:x?} before instruction {i} at {:#x}",
                        snap[0]
                    );
                    for l in 0..NLOCS as usize {
                        if snap[1 + l] != st[l] {
                            println!(
                                "  {}: pcalls {:#x} pmem {:#x}",
                                super::NAMES[l],
                                snap[1 + l],
                                st[l]
                            );
                        }
                    }
                    ok = false;
                    break;
                }
                let s = pm.step();
                steps += 1;
                if s != 0 && i + 1 != tr.len() / (1 + NLOCS as usize) {
                    println!("P-mem stopped with {s} early");
                    ok = false;
                    break;
                }
            }
            let s_m = pm.step();
            let fin_c: Vec<u64> = (0..NLOCS).map(|l| lk.sim.get(l)).collect();
            let fin_m: Vec<u64> = (0..NLOCS).map(|l| pm.get(l)).collect();
            if ok && (st_c != 1 || s_m != 1 || fin_c != fin_m) {
                println!("DIVERGE {name}{args:x?} at end: status {st_c}/{s_m}");
                ok = false;
            }
            if !ok {
                fails += 1;
            }
        }
    }
    println!(
        "lockstep P-calls vs P-mem: {} functions x {per} runs, {steps} instructions compared, {fails} divergences",
        funcs.len()
    );
    if fails > 0 {
        bail!("divergences");
    }
    Ok(())
}

