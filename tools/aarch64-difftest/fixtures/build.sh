#!/usr/bin/env bash
# The A64 instruction words of the three AArch64 fixtures (untrusted tooling).
#
#   tools/aarch64-difftest/fixtures/build.sh           # print the listing
#   tools/aarch64-difftest/fixtures/build.sh --check   # the listing equals pinned/words.txt
#
# Compiles `sat_add_u32` and `clamp_i32` (examples/elf-ladder/01-leaf-arith/arith.c) and `strlen`
# (examples/elf-ladder/common/libmini.c) in the corpus toolchain image (corpus/toolchain/image.sh
# builds it) and prints one line per instruction: offset from the function's start, the 32-bit
# word, the disassembly. The code-generation flags are `-O2 -fno-tree-loop-distribute-patterns`
# and nothing else; `-I` and `-c` are only what a compile-to-object needs. The sources are mounted
# read-only and the objects stay in the container. Needs Docker.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
IMAGE=silmaril-corpus-toolchain:trixie-20251103
PINNED=$HERE/pinned/words.txt

listing() {
  docker run --rm --network none -v "$ROOT/examples/elf-ladder:/src:ro" "$IMAGE" bash -c '
    set -euo pipefail
    export LC_ALL=C TZ=UTC
    TP=aarch64-linux-gnu-
    CFLAGS="-O2 -fno-tree-loop-distribute-patterns"
    cd /tmp
    ${TP}gcc $CFLAGS -I/src/common -c /src/01-leaf-arith/arith.c -o arith.o
    ${TP}gcc $CFLAGS -I/src/common -c /src/common/libmini.c -o libmini.o

    sha() { sha256sum "$1" | cut -d" " -f1; }
    echo "# AArch64 fixture words. Generated by tools/aarch64-difftest/fixtures/build.sh; do not edit."
    echo "# compiler:  $(${TP}gcc --version | head -n1) [gcc-14-aarch64-linux-gnu $(dpkg-query -W -f "\${Version}" gcc-14-aarch64-linux-gnu)]"
    echo "# assembler: $(${TP}as --version | head -n1) [binutils-aarch64-linux-gnu $(dpkg-query -W -f "\${Version}" binutils-aarch64-linux-gnu)]"
    echo "# command:   ${TP}gcc $CFLAGS -I examples/elf-ladder/common -c <source>"
    echo "# branch protection (gcc -Q --help=target): $(${TP}gcc $CFLAGS -Q --help=target | awk "/-mbranch-protection=/ { print (\$2 == \"\" ? \"none\" : \$2) }")"
    echo "# source: examples/elf-ladder/01-leaf-arith/arith.c sha256 $(sha /src/01-leaf-arith/arith.c)"
    echo "# source: examples/elf-ladder/common/libmini.c sha256 $(sha /src/common/libmini.c)"
    echo "# source: examples/elf-ladder/common/rt.h sha256 $(sha /src/common/rt.h)"
    echo "# source: examples/elf-ladder/01-leaf-arith/arith.h sha256 $(sha /src/01-leaf-arith/arith.h)"
    echo "# object: arith.o sha256 $(sha arith.o)"
    echo "# object: libmini.o sha256 $(sha libmini.o)"
    echo "# line: <offset from the function start> <word> <disassembly>. A word is the 32-bit"
    echo "# instruction; in memory it is stored as four bytes, least significant first."

    # words OBJECT SYMBOL: the instructions of one function. Fails on a missing symbol, an
    # empty function or a relocation (the three fixtures are leaves and need none).
    words() {
      ${TP}objdump -d -r --disassemble="$2" "$1" | awk -v sym="$2" -v obj="$1" '\''
        # The image has mawk: no strtonum, no gensub.
        function hex(s,   i, v) {
          v = 0
          for (i = 1; i <= length(s); i++) v = v * 16 + index("0123456789abcdef", substr(s, i, 1)) - 1
          return v
        }
        /R_AARCH64_/ { print "error: " obj ": " sym ": unexpected relocation: " $0 > "/dev/stderr"; bad = 1 }
        $0 ~ "^[0-9a-f]+ <" sym ">:$" { base = hex($1); print ""; print sym ":  (" obj ")"; next }
        /^ *[0-9a-f]+:\t[0-9a-f]+ / && length($2) == 8 {
          addr = $1; sub(/:$/, "", addr); word = $2
          text = $0; sub(/^[^\t]*\t[^\t]*\t/, "", text)      # drop address and word
          sub(/[ \t]*\/\/.*$/, "", text)                      # drop the disassembler comment
          gsub(/[ \t]+/, " ", text)
          if (match(text, / [0-9a-f]+ <[^>]+>$/)) {           # branch target: keep <sym+off>
            target = substr(text, RSTART); sub(/^ [0-9a-f]+/, "", target)
            text = substr(text, 1, RSTART - 1) target
          }
          printf "  0x%02x  %s  %s\n", hex(addr) - base, word, text
          n++
        }
        END { if (n == 0) { print "error: " obj ": no instructions for " sym > "/dev/stderr"; bad = 1 }
              exit bad }'\''
    }
    words arith.o sat_add_u32
    words arith.o clamp_i32
    words libmini.o strlen
  '
}

case ${1:-} in
  '') listing ;;
  --check)
    if listing | cmp - "$PINNED"; then echo "ok ${PINNED#"$ROOT"/}"
    else echo "error: the listing differs from ${PINNED#"$ROOT"/}" >&2; exit 1; fi ;;
  *) sed -n '2,5p' "$0"; exit 2 ;;
esac
