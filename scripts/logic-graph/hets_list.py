#!/usr/bin/env python3
"""Write silmaril/logic-graph/hets.toml: the logics and comorphisms of the Hets logic graph at a
pinned Hets commit, as Hets lists them (`logicList` in Comorphisms/LogicList.hs and
`comorphismList` in Comorphisms/LogicGraph.hs), with the CPP flag guarding each entry.

Only names are copied: which logics and comorphisms Hets registers, and the source and target
logic of each comorphism (read from `sourceLogic`/`targetLogic` in its module). No Hets code is
copied. Hets is GPL-2.0 (https://github.com/spechub/Hets); its names are cited, not vendored.

    python3 -I scripts/logic-graph/hets_list.py SRC_DIR > silmaril/logic-graph/hets.toml
    python3 -I scripts/logic-graph/hets_list.py SRC_DIR --check

SRC_DIR is a checkout (or a partial copy) of Hets at HETS_REV: Comorphisms/LogicList.hs,
Comorphisms/LogicGraph.hs and the comorphism modules they import. The two list files are checked
against their SHA-256 below.
"""
import hashlib, pathlib, re, sys

HETS_REV = "65ca27f4fcafd57f94fbb0908f2d88a16b0977ea"
SHA256 = {
    "Comorphisms/LogicList.hs": "9980fc8ac0a721aba947a45cb05a0389cca7f23b4ae81539b6ef9ef56e9d38a1",
    "Comorphisms/LogicGraph.hs": "47cb437014bb0056b01e5815768d2a003c3d06fa9ab57230c4ccea25b5e06b78",
}
# Hets's Haskell logic identifiers, as `sourceLogic`/`targetLogic` return them, to the logic's name.
LOGIC_IDS = {"PLogic": "Propositional", "CLogic": "CASL", "CASL_Logic": "CASL", "ClLogic": "CommonLogic",
             "QLogic": "QBF", "MLogic": "Maude", "FOLLogic": "SoftFOL", "OWLLogic": "OWL2",
             "Logic": "CommonLogic", "GenCspCASL": "cspCASL"}


def entries(text, start):
    """The entries of the Haskell list after `start`, with the CPP flag guarding each."""
    body = text[text.index(start):]
    body = body[:body.index("]") + 1] if start.startswith("logicList") else body[:body.index(" ]") + 2]
    flags, out = [], []
    for line in body.splitlines()[1:]:
        s = line.strip()
        if s.startswith("#ifdef ") or s.startswith("#ifndef "):
            flags.append(("not " if s.startswith("#ifndef") else "") + s.split()[1])
        elif s.startswith("#endif"):
            flags.pop()
        else:
            m = re.match(r"^[\[,]\s*(Logic|Comorphism)\s+(.*?)\s*(--.*)?\]?$", s)
            if m:
                out.append((m.group(2).rstrip("]").strip().lstrip("$ ").strip(), " and ".join(flags) or None))
    return out


def slug(s):
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s if s[:1].isalpha() else "x" + s


def main():
    src = pathlib.Path(sys.argv[1])
    for f, h in SHA256.items():
        got = hashlib.sha256((src / f).read_bytes()).hexdigest()
        if got != h:
            sys.exit(f"{f}: sha256 {got}, expected {h} (Hets {HETS_REV})")
    logics = entries((src / "Comorphisms/LogicList.hs").read_text(), "logicList =")
    comors = entries((src / "Comorphisms/LogicGraph.hs").read_text(), "comorphismList =")
    # source and target logics, from each module's instance declarations
    ends = {}
    for f in sorted(src.rglob("*.hs")):
        t = f.read_text(errors="replace")
        for m in re.finditer(r"sourceLogic\s+\(?(\w+)[^=\n]*=\s*(\w+)", t):
            ends.setdefault(m.group(1), [None, None])[0] = m.group(2)
        for m in re.finditer(r"targetLogic\s+\(?(\w+)[^=\n]*=\s*(\w+)", t):
            ends.setdefault(m.group(1), [None, None])[1] = m.group(2)
        if f.name in ("HolLight2Isabelle.hs", "Haskell2IsabelleHOLCF.hs"):
            for m in re.finditer(r"instance Comorphism\s+(\w+)", t):
                s = re.search(r"sourceLogic _ = (\w+)", t).group(1)
                d = re.search(r"targetLogic _ = (\w+)", t).group(1)
                ends[m.group(1)] = [s, d]
    out = ["# The Hets logic graph, as Hets lists it. Generated by scripts/logic-graph/hets_list.py from",
           f"# https://github.com/spechub/Hets at {HETS_REV}: do not edit by hand.",
           "# Each comorphism names its source and target logic as Hets does; a sublogic (CFOL, SubCFOL,",
           "# THFP, ...) is named by its logic. Names only: no Hets code is copied (Hets is GPL-2.0).",
           'schema = "silmaril.records.v0.2"', ""]
    seen = set()
    for name, flag in logics:
        n = slug(name)
        out += ["[[hets_logic]]", f'name = "hets.logic.{n}"', f'hets_name = "{name}"']
        if flag:
            out.append(f'flag = "{flag}"')
        out += ['hets_file = "Comorphisms/LogicList.hs"', f'hets_rev = "{HETS_REV}"', ""]
        seen.add(name)
    for expr, flag in comors:
        cid = re.split(r"[\s(]", expr.strip("()"))[0]
        key = {"cspCASLTrace": "CspCASL2CspCASL", "cspCASLFailure": "CspCASL2CspCASL",
               "suleCFOL2SoftFOL": "GenSuleCFOL2SoftFOL", "suleCFOL2SoftFOLInduction": "GenSuleCFOL2SoftFOL",
               "suleCFOL2SoftFOLInduction2": "GenSuleCFOL2SoftFOL", "suleCFOL2TPTP": "GenSuleCFOL2TPTP",
               "CL2CFOL": "CL2CFOL", "Haskell2IsabelleHOLCF": "Haskell2IsabelleHOLCF",
               "Haskell2IsabelleHOL": "Haskell2IsabelleHOLCF"}.get(cid, cid)
        s, d = ends.get(key, [None, None])
        if key in ("Haskell2IsabelleHOLCF",):
            s, d = "Haskell", "Isabelle"
        if key == "HolLight2Isabelle":
            s, d = "HolLight", "Isabelle"
        if cid in ("cspCASLTrace", "cspCASLFailure"):
            # CspCASL2CspCASL () Trace / Failure: GenCspCASL () to GenCspCASL Trace / Failure
            s, d = "cspCASL", {"cspCASLTrace": "traceCspCASL", "cspCASLFailure": "failureCspCASL"}[cid]
        s, d = LOGIC_IDS.get(s, s), LOGIC_IDS.get(d, d)
        if s is None or d is None:
            sys.exit(f"no source/target logic for {expr}")
        out += ["[[hets_comorphism]]", f'name = "hets.comorphism.{slug(expr)}"', f'hets_name = "{expr}"',
                f'hets_from = "{s}"', f'hets_to = "{d}"']
        if flag:
            out.append(f'flag = "{flag}"')
        out += ['hets_file = "Comorphisms/LogicGraph.hs"', f'hets_rev = "{HETS_REV}"', ""]
    text = "\n".join(out)
    if "--check" in sys.argv:
        path = pathlib.Path(__file__).resolve().parents[2] / "silmaril/logic-graph/hets.toml"
        if path.read_text() != text:
            sys.exit(f"{path} is stale")
    else:
        sys.stdout.write(text)


main()
