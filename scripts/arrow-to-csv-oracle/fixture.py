"""Verify the checked-in Lean fixture, or regenerate with the pinned producers."""

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import platform
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MANIFEST = json.loads((HERE / "fixture.json").read_text(encoding="utf-8"))
TARGET = ROOT / MANIFEST["lean_fixture"]
CHUNK = 64


def generate():
    import numpy as np
    import pyarrow as pa

    producer = MANIFEST["producer"]
    assert platform.python_implementation() == "CPython"
    assert platform.python_version() == producer["python"]
    assert pa.__version__ == pa.cpp_build_info.version == producer["pyarrow"]
    assert np.__version__ == producer["numpy"]

    kinds = {"int32": pa.int32(), "utf8": pa.string()}
    schema = pa.schema([
        pa.field(field["name"], kinds[field["type"]], nullable=field["nullable"])
        for field in MANIFEST["fields"]
    ])
    options = pa.ipc.IpcWriteOptions(
        metadata_version=pa.ipc.MetadataVersion.V5, use_legacy_format=False, compression=None
    )
    sink = pa.BufferOutputStream()
    with pa.ipc.new_stream(sink, schema, options=options) as stream:
        for rows in MANIFEST["batches"]:
            arrays = [pa.array([row[i] for row in rows], type=field.type) for i, field in enumerate(schema)]
            stream.write_batch(pa.RecordBatch.from_arrays(arrays, schema=schema))
    ipc_bytes = sink.getvalue().to_pybytes()

    with pa.ipc.open_stream(ipc_bytes) as stream:
        assert stream.schema == schema
        names = stream.schema.names
        batches = [[[row[name] for name in names] for row in batch.to_pylist()] for batch in stream]
    assert batches == MANIFEST["batches"]
    records = [names] + [
        ["N" if value is None else "T" + str(value) for value in row]
        for batch in batches
        for row in batch
    ]
    buffer = io.StringIO(newline="")
    csv.writer(buffer, quoting=csv.QUOTE_ALL, lineterminator="\r\n").writerows(records)
    csv_bytes = buffer.getvalue().encode("ascii")
    assert list(csv.reader(io.StringIO(csv_bytes.decode("ascii"), newline=""))) == records
    return {"ipc": ipc_bytes, "csv": csv_bytes}


def render(data):
    lines = [
        "module",
        "",
        "public meta import Silmaril.Prelude.Bytes.Defs",
        "",
        "/-! Generated by scripts/arrow-to-csv-oracle/fixture.py. -/",
        "",
        "public section",
        "",
        "namespace Silmaril.Formats.Arrow.ToCsv.Fixture",
        "",
    ]
    for name, raw in data.items():
        lines.append(f"meta def {name} : KBytes := KBytes.ofChunks {CHUNK} {len(raw)} [")
        for start in range(0, len(raw), CHUNK):
            number = int.from_bytes(raw[start:start + CHUNK], "little")
            suffix = "," if start + CHUNK < len(raw) else "]"
            lines.append(f"  {number:#x}{suffix}")
        lines.append("")
    lines.extend(["end Silmaril.Formats.Arrow.ToCsv.Fixture", ""])
    return "\n".join(lines)


def read_fixture():
    lean = TARGET.read_text(encoding="utf-8")
    data = {}
    for name in ("ipc", "csv"):
        pattern = rf"meta def {name} : KBytes := KBytes.ofChunks {CHUNK} (\d+) \[([^\]]+)\]"
        match = re.search(pattern, lean)
        assert match, name
        length = int(match[1])
        chunks = [int(word, 16) for word in re.findall(r"0x[0-9a-f]+", match[2])]
        assert len(chunks) == (length + CHUNK - 1) // CHUNK
        data[name] = b"".join(
            word.to_bytes(min(CHUNK, length - i * CHUNK), "little")
            for i, word in enumerate(chunks)
        )
    assert render(data) == lean
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--regenerate", action="store_true")
    args = parser.parse_args()
    data = generate() if args.regenerate else read_fixture()
    for name, raw in data.items():
        digest = hashlib.sha256(raw).hexdigest()
        if digest != MANIFEST[f"{name}_sha256"]:
            raise SystemExit(f"{name}: unexpected SHA-256 {digest}")
        print(f"{name}: {len(raw)} bytes SHA-256 {digest}")
    if args.regenerate:
        TARGET.write_text(render(data), encoding="utf-8")


if __name__ == "__main__":
    main()
